func TestRunEnvOverlay(t *testing.T) {
	dir := t.TempDir()
	schema := writeFile(t, dir, "schema.env", "# @package=config\n# @out(path=env.go)\nDB_HOST=base\n")

	out := filepath.Join(dir, "env.go")

	writeFile(t, dir, ".env.local", "DB_HOST=local\n")
	writeFile(t, dir, ".env.prod", "DB_HOST=prod\nNEW_KEY=added\n")

	code, _, _ := runWith(t, "-schema", schema)
	if code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}

	src := readFile(t, out)

	if !strings.Contains(string(src), `"local"`) {
		t.Errorf("default overlay .env.local not applied, got:\n%s", src)
	}

	code, _, _ = runWith(t, "-schema", schema, "-env", "prod", "-force")
	if code != 0 {
		t.Fatalf("exit code = %d, want 0", code)
	}

	src = readFile(t, out)

	if !strings.Contains(string(src), `"prod"`) {
		t.Errorf("-env prod overlay not applied, got:\n%s", src)
	}

	if !strings.Contains(string(src), `m["NEW_KEY"]`) {
		t.Errorf("-env prod overlay did not add NEW_KEY, got:\n%s", src)
	}
}

