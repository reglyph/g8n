func TestResolveOutputs(t *testing.T) {
	dir := t.TempDir()
	schemaPath := filepath.Join(dir, "schema.env")

	schema := &parser.Schema{Package: "spkg", OutPath: "rel/env.go"}

	if pkg, out, err := resolveOutputs(schemaPath, schema, "fpkg", ""); err != nil || pkg != "fpkg" || out != filepath.Join(dir, "rel/env.go") {
		t.Errorf("flag package discarded: pkg = %q, out = %q, err = %v", pkg, out, err)
	}

	if pkg, out, err := resolveOutputs(schemaPath, schema, "", ""); err != nil || pkg != "spkg" || out != filepath.Join(dir, "rel/env.go") {
		t.Errorf("schema package/@out not used: pkg = %q, out = %q, err = %v", pkg, out, err)
	}

	noOut := &parser.Schema{}

	if _, _, err := resolveOutputs(schemaPath, noOut, "", ""); err == nil || !strings.Contains(err.Error(), "no out path") {
		t.Errorf("want no out path error, got %v", err)
	}

	if pkg, out, err := resolveOutputs(schemaPath, noOut, "", "my-dir/env.go"); err != nil || pkg != "mydir" || out != "my-dir/env.go" {
		t.Errorf("derived package = %q, out = %q, err = %v, want mydir", pkg, out, err)
	}
}

