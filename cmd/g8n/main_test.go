func TestWriteIfChanged(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "env.go")
	src := []byte("// code\n")

	var stderr bytes.Buffer

	if err := writeIfChanged(path, src, false, &stderr); err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(stderr.String(), "wrote") {
		t.Errorf("first write stderr = %q, want wrote", stderr.String())
	}

	stderr.Reset()

	if err := writeIfChanged(path, src, false, &stderr); err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(stderr.String(), "up to date") {
		t.Errorf("unchanged stderr = %q, want up to date", stderr.String())
	}

	got := readFile(t, path)

	if string(got) != string(src) {
		t.Errorf("unchanged run must not modify the file")
	}

	stderr.Reset()

	if err := writeIfChanged(path, src, true, &stderr); err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(stderr.String(), "refreshed") {
		t.Errorf("force stderr = %q, want refreshed", stderr.String())
	}

	stderr.Reset()

	if err := writeIfChanged(path, []byte("// new\n"), false, &stderr); err != nil {
		t.Fatal(err)
	}

	if !strings.Contains(stderr.String(), "wrote") {
		t.Errorf("changed stderr = %q, want wrote", stderr.String())
	}

	got = readFile(t, path)

	if string(got) != "// new\n" {
		t.Errorf("file not updated, got %q", got)
	}
}

