func writeFile(t *testing.T, dir, name, content string) string {
	t.Helper()

	path := filepath.Join(dir, name)

	// #nosec G301 -- test fixtures use the account's default umask
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}

	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}

	return path
}

func readFile(t *testing.T, path string) string {
	t.Helper()

	// #nosec G304 -- reading back files written by the test itself
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	return string(data)
}

func runWith(t *testing.T, args ...string) (code int, stdout, stderr string) {
	t.Helper()

	var out, errBuf bytes.Buffer

	code = run(args, &out, &errBuf)

	return code, out.String(), errBuf.String()
}

func TestBasePackageName(t *testing.T) {
	cases := []struct {
		name string
		out  string
		want string
	}{
		{"defaults to env for empty dir", "env.go", "env"},
		{"derives from directory", "internal/config/env.go", "config"},
		{"strips hyphens", "work/api-key/env.go", "apikey"},
		{"prefixes leading digit", "out/2fa/env.go", "env_2fa"},
		{"strips dots", "out/my.dir/env.go", "mydir"},
		{"root directory", "/env.go", "env"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := basePackageName(tc.out)
			if err != nil {
				t.Fatalf("basePackageName(%q): %v", tc.out, err)
			}

			if got != tc.want {
				t.Errorf("basePackageName(%q) = %q, want %q", tc.out, got, tc.want)
			}
		})
	}
}

func TestBasePackageNameRejectsKeywords(t *testing.T) {
	for _, kw := range []string{"type", "func", "range", "select"} {
		_, err := basePackageName("work/" + kw + "/env.go")
		if err == nil {
			t.Errorf("basePackageName(work/%s/env.go): expected error for Go keyword", kw)
		}
	}
}

